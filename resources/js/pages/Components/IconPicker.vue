// Filtered list based on search term
const filteredIcons = computed(() => {
    if (!searchQuery.value) return allIcons.value;
    const q = searchQuery.value.toLowerCase().trim();
    return allIcons.value.filter((icon) => icon.includes(q));
});

// Group icons into rows of 5 for virtual grid rendering
const iconRows = computed(() => {
    const list = filteredIcons.value;
    const rows = [];
    for (let i = 0; i < list.length; i += 5) {
        rows.push(list.slice(i, i + 5));
    }
    return rows;
});

const toggle = (event) => {
    popoverRef.value.toggle(event);
};

const selectIcon = (icon) => {
    emit('update:modelValue', icon);
    popoverRef.value.hide();
};

const clearIcon = () => {
    emit('update:modelValue', '');
};
</script>

