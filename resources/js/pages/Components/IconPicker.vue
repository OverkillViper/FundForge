            class="flex h-11 items-center gap-2 px-3 py-2"
        >
            <i
                v-if="modelValue"
                :class="`icon-${modelValue} text-xl text-primary`"
            ></i>
            <i v-else class="icon-circle text-xl text-gray-400"></i>

            <span v-if="showLabel" class="max-w-28 truncate text-xs capitalize">
                {{ modelValue ? modelValue : 'Select Icon' }}
            </span>

            <i class="pi pi-chevron-down text-xs opacity-60"></i>
        </Button>

        <!-- Clear Selection Button -->
        <Button
            v-if="modelValue"
